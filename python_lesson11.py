# Задача 10: Функция с map() и функцией-аргументом
# 1. Напишите функцию apply_operation(operation, *numbers)
# 2. operation — функция, которую применять
# 3. numbers — числа, к которым применять функцию
# 4. Используйте map() для применения функции
# 5. Возвращайте список результатов
#
# Пример:
# def double(x):
#     return x * 2
#
# apply_operation(double, 1, 2, 3, 4, 5)
# → [2, 4, 6, 8, 10]
#
# def square(x):
#     return x ** 2
#
# apply_operation(square, 1, 2, 3, 4, 5)
# → [1, 4, 9, 16, 25]


def apply_operation(operation, *numbers):
    return list(map(operation, numbers))  # Преобразуем результат map в список и возвращаем


# Функция, которая удваивает число
def double(x):
    return x * 2  # Возвращает число умноженное на 2


# Функция, которая возводит число в квадрат
def square(x):  # Принимает одно число
    return x ** 2  # Возвращает число в квадрате (x в степени 2)


# Тестируем функцию apply_operation с функцией double
# double передаётся как аргумент (без скобок!)
print(apply_operation(double, 1, 2, 3, 4, 5))  
# Тестируем с функцией square
print(apply_operation(square, 1, 2, 3, 4, 5))  